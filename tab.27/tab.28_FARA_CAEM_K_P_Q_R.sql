-- Tab.28 - varianta cu excluderea CAEM2 principal K, P, Q, R.
-- Prioritate: ID_MD=61832, COL31 (CAEM2 actualizat); fallback: CIS2.RENIM.CAEM2.
-- Top 5 general este recalculat dupa filtrarea la sectiunile B,C,D,E,F,G,H,I,J,L,M,N,S.
-- Top 5 pe fiecare sectiune este filtrat prin clasificator pe acelasi CAEM actualizat.
-- Indicatori si sursa CIS2.VW_DATA_ALL_COEF sunt pastrate ca in tab.28.sql original.

INSERT INTO CIS2.TABLE_OUT 
(
  PERIOADA,
  FORM,
  FORM_VERS,
  ID_MDTABLE,
  COD_CUATM,
  NR_SECTIE,
  NUME_SECTIE,
  NR_SECTIE1,
  NUME_SECTIE1,
  NR_SECTIE2,
  NUME_SECTIE2,
  NR_ROW,
  ORDINE,
  DECIMAL_POS,
  NUME_ROW,  
 COL1, COL2
)

SELECT 
 
:PPERIOADA AS PERIOADA,
:PFORM AS FORM,
:PFORM_VERS AS FORM_VERS,
:PID_MDTABLE AS ID_MDTABLE,
:PCOD_CUATM AS COD_CUATM,    
'0' AS  NR_SECTIE,
'0' AS  NUME_SECTIE,
'1' AS NR_SECTIE1,
'Total' AS NUME_SECTIE1,
'0' AS NR_SECTIE2,
'0' AS NUME_SECTIE2, 
'00000'||'~'||D.R150 AS NR_ROW,
 D.R150 AS ORDINE,
'01' AS DECIMAL_POS,
 D.NUME_ROW AS NUME_ROW,
 D.CUIIO AS COL1, D.COL3 AS COL2
 FROM (

    
SELECT 
   DISTINCT DD.CUIIO,   DD.NUME_ROW, 
    
   DD.PERIOADA,DD.CUATM_FULL,DD.FORM_VERS,DD.FORM, COL3,  
   ROW_NUMBER() OVER ( ORDER BY DD.COL3  DESC NULLS LAST ) AS R150 
   
FROM(
   SELECT DISTINCT D.CUIIO, D.NUME_ROW,D.CUIIO_VERS,D.COL3,D.FORM, D.FORM_VERS, D.CUATM_FULL, D.PERIOADA,
   CASE WHEN D.CAEM2_ACTUALIZAT IS NULL THEN D.CAEM2 ELSE D.CAEM2_ACTUALIZAT END AS CAEM2
       
   FROM(
SELECT  
 DISTINCT D.CUIIO, D.CUIIO_VERS, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,R.DENUMIRE AS NUME_ROW,
 MAX(CASE WHEN D.ID_MD = 61832 THEN D.COL31 END) AS CAEM2_ACTUALIZAT,
 MAX(SUBSTR(R.CAEM2,2,4)) AS CAEM2, 
  
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150') THEN  CIS2.NVAL(D.COL1) END)) AS COL3,
  
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (100)  AND D.RIND IN ('CD') THEN  D.COL1 ELSE 0 END)) AS CD

   
FROM   
    CIS2.VW_DATA_ALL_COEF D  
    INNER JOIN CIS2.RENIM R ON (D.CUIIO = R.CUIIO)
      INNER JOIN 
          (
            SELECT R.CUIIO, MAX(R.CUIIO_VERS) AS CUIIO_VERS
            FROM CIS2.RENIM R WHERE R.CUIIO_VERS <= :pPERIOADA
            GROUP BY R.CUIIO
          ) TR ON (TR.CUIIO = R.CUIIO AND TR.CUIIO_VERS = R.CUIIO_VERS)      
      
WHERE
  D.FORM IN (64)             AND 
  D.FORM_VERS = :PFORM_VERS  AND      
  D.PERIOADA =:PPERIOADA     AND
  D.CUATM_FULL LIKE '%'||:PCOD_CUATM||';%'   AND
  D.CAPITOL IN (100,1124,1127,1129) -- and d.cuiio in (40381696)
--  and d.cuiio in (40209448)
 GROUP BY D.CUIIO,D.CUIIO_VERS, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,R.DENUMIRE
 
 HAVING   
 (
   SUM(CASE WHEN D.ID_MD IN (62382) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) =  1 
   OR 
   SUM(CASE WHEN D.ID_MD IN (114171,62413) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) >  0  
      )
 )D) DD 
  
  
  WHERE 
  (DD.FORM=:pFORM) AND
  (DD.FORM_VERS=:pFORM_VERS) AND
  (:pID_MDTABLE=:pID_MDTABLE) AND
  (DD.CUATM_FULL LIKE '%'||:pCOD_CUATM||';%') AND   
  DD.PERIOADA IN (:pPERIOADA)
  -- Acelasi CAEM actualizat ca pentru randurile pe sectiuni.
  -- Filtrul este aplicat INAINTE de ROW_NUMBER() pentru Top 5 global.
  AND EXISTS (
      SELECT 1
      FROM CIS2.VW_CL_CAEM2 C_F
      WHERE SUBSTR(C_F.CODUL, 2, 4) = DD.CAEM2
        AND SUBSTR(C_F.CODUL, 1, 1) IN
            ('B','C','D','E','F','G','H','I','J','L','M','N','S')
        AND SUBSTR(C_F.CODUL, 1, 3) NOT IN ('S94', 'K65')
        AND C_F.CODUL NOT IN ('K6419', 'K6411')
  )
) D
WHERE D.R150 BETWEEN 1 AND 5

UNION

SELECT 
 
:PPERIOADA AS PERIOADA,
:PFORM AS FORM,
:PFORM_VERS AS FORM_VERS,
:PID_MDTABLE AS ID_MDTABLE,
:PCOD_CUATM AS COD_CUATM,    
'0' AS  NR_SECTIE,
'0' AS  NUME_SECTIE,
'2' AS NR_SECTIE1,
'Pe CAEM2' AS NUME_SECTIE1,
'0' AS NR_SECTIE2,
'0' AS NUME_SECTIE2, 
D.CAEM||'~'||D.CUIIO AS NR_ROW,
 ROWNUM AS ORDINE,
'01' AS DECIMAL_POS,
 D.NUME_ROW AS NUME_ROW,
 D.CUIIO AS COL1, D.COL3 AS COL2
 FROM (

    
SELECT 
   DISTINCT DD.CUIIO,   DD.NUME_ROW, CC.FULL_CODE ,
   SUBSTR(C.CODUL,1,1)||CAEM2 AS CAEM,    
   DD.PERIOADA,DD.CUATM_FULL,DD.FORM_VERS,DD.FORM, COL3,  
   ROW_NUMBER() OVER (PARTITION BY SUBSTR(C.CODUL,1,1) ORDER BY DD.COL3  DESC NULLS LAST ) AS R150 
   
FROM(
   SELECT DISTINCT D.CUIIO, D.NUME_ROW,D.CUIIO_VERS,D.COL3,D.FORM, D.FORM_VERS, D.CUATM_FULL, D.PERIOADA,
   CASE WHEN D.CAEM2_ACTUALIZAT IS NULL THEN D.CAEM2 ELSE D.CAEM2_ACTUALIZAT END AS CAEM2
       
   FROM(
SELECT  
 DISTINCT D.CUIIO, D.CUIIO_VERS, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,R.DENUMIRE AS NUME_ROW,
 MAX(CASE WHEN D.ID_MD = 61832 THEN D.COL31 END) AS CAEM2_ACTUALIZAT,
 MAX(SUBSTR(R.CAEM2,2,4)) AS CAEM2, 
  
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150') THEN  CIS2.NVAL(D.COL1) END)) AS COL3,
  
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (100)  AND D.RIND IN ('CD') THEN  D.COL1 ELSE 0 END)) AS CD

   
FROM   
    CIS2.VW_DATA_ALL_COEF D  
    INNER JOIN CIS2.RENIM R ON (D.CUIIO = R.CUIIO)
      INNER JOIN 
          (
            SELECT R.CUIIO, MAX(R.CUIIO_VERS) AS CUIIO_VERS
            FROM CIS2.RENIM R WHERE R.CUIIO_VERS <= :pPERIOADA
            GROUP BY R.CUIIO
          ) TR ON (TR.CUIIO = R.CUIIO AND TR.CUIIO_VERS = R.CUIIO_VERS)      
      
WHERE
  D.FORM IN (64)             AND 
  D.FORM_VERS = :PFORM_VERS  AND      
  D.PERIOADA =:PPERIOADA     AND
  D.CUATM_FULL LIKE '%'||:PCOD_CUATM||';%'   AND
  D.CAPITOL IN (100,1124,1127,1129) -- and d.cuiio in (40381696)
  --  and d.cuiio in (40209448)
  
 GROUP BY D.CUIIO,D.CUIIO_VERS, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,R.DENUMIRE
 
 HAVING   
 
-- CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (100)  AND D.RIND IN ('CD') THEN  D.COL1 ELSE 0 END)) >0 
  (
   SUM(CASE WHEN D.ID_MD IN (62382) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) =  1 
   OR 
   SUM(CASE WHEN D.ID_MD IN (114171,62413) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) >  0  
      )
 )D) DD 
  INNER JOIN (
  SELECT
CODUL, 
DENUMIRE, 
GRUPA, 
ORDINE, 
FULL_CODE, 
NUM_CODE, 
PRIM                
                FROM  CIS2.VW_CL_CAEM2
                
               
                
                WHERE 
                
                
(
                CODUL LIKE 'C%'
                OR CODUL LIKE 'B%'
                OR CODUL LIKE 'D%'
                OR CODUL LIKE 'E%'
                OR CODUL LIKE 'F%'
                OR CODUL LIKE 'G%'
                OR CODUL LIKE 'H%'
                OR CODUL LIKE 'I%'

                OR CODUL LIKE 'J%'
                OR CODUL LIKE 'L%'
                OR CODUL LIKE 'M%'

                OR CODUL LIKE 'N%'

                OR CODUL LIKE 'S%'
                )
                
                AND 
                
                SUBSTR(CODUL,1,3) NOT IN ('S94','K65')
                AND 
                CODUL NOT IN ('K6419','K6411')
  ) C ON SUBSTR(C.CODUL,2,4)  = DD.CAEM2
  INNER JOIN CIS2.VW_CL_CAEM2 CC ON(CC.FULL_CODE LIKE '%'||C.CODUL||';%')
  
  WHERE 
  (DD.FORM=:pFORM) AND
  (DD.FORM_VERS=:pFORM_VERS) AND
  (:pID_MDTABLE=:pID_MDTABLE) AND
  (DD.CUATM_FULL LIKE '%'||:pCOD_CUATM||';%') AND   
  DD.PERIOADA IN (:pPERIOADA) 
  
   ORDER BY CC.FULL_CODE 
   
   ) D
  
         
 --D
