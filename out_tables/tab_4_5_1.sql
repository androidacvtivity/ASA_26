INSERT INTO CIS2.TABLE_OUT 
(
  PERIOADA,
  FORM,
  FORM_VERS,
  ID_MDTABLE,
  COD_CUATM,
  NR_SECTIE,
  NUME_SECTIE,
  NR_SECTIE1,
  NUME_SECTIE1,
  NR_SECTIE2,
  NUME_SECTIE2,
  NR_ROW,
  ORDINE,
  DECIMAL_POS,
  NUME_ROW,  
  COL1, COL2, COL3,COL4,COL5
)

     
SELECT 
:pPERIOADA AS PERIOADA,
:pFORM AS FORM,
:pFORM_VERS AS FORM_VERS,
:pID_MDTABLE AS ID_MDTABLE,
:pCOD_CUATM AS COD_CUATM,    
CFP AS NR_SECTIE,
CFP ||'-'||CFP_DEN AS NUME_SECTIE,  
'0' AS NR_SECTIE1,
'0' AS NUME_SECTIE1,
'0' AS NR_SECTIE2,
'0' AS NUME_SECTIE2, 
NR_ROW AS NR_ROW,
ROWNUM AS ORDINE,
'00000' AS DECIMAL_POS,
NUME_ROW,
COL1, COL2, COL3,COL4,COL5
FROM
(

SELECT 
   CFF.CODUL AS CFP,
   CFF.DENUMIRE AS CFP_DEN,
   CC.FULL_CODE,
   CC.DENUMIRE AS NUME_ROW,
   CC.CODUL AS NR_ROW,
   CC.FULL_CODE AS ORDINE,
   -- Make roudn 0.2
   SUM(DD.COL0) AS COL1,
   SUM(DD.COL2) AS COL2,
   SUM(DD.COL3) AS COL3,
   SUM(DD.COL4) AS COL4,
   SUM(DD.COL5) AS COL5
   
  
   


    FROM 
  (
-------------------------------------------------------------------------------
SELECT 
 
 DISTINCT 
 D.CUIIO, 
 --SUM(CASE WHEN D.ID_MD IN (114173,114171,62382,62413) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) AS COL0,
 SUM(CASE WHEN D.CAPITOL IN (100) AND D.RIND IN ('CD') THEN D.COL1 ELSE 0 END) AS COL0,
 MAX( CASE WHEN  D.RIND IN ('8') AND D.CAPITOL IN (1129) THEN D.COL31 END )  AS CAEM2_ACTUALIZAT,
 MAX(SUBSTR(D.CAEM2,2,4))  AS CAEM2,
 CASE WHEN  MAX(CASE WHEN D.ID_MD = 61832 THEN D.COL31 END) IS NULL THEN 
 SUBSTR(R.CAEM2,2,4) ELSE  MAX(CASE WHEN D.ID_MD = 61832 THEN D.COL31 END) END  AS CAEM_FINAL,
 D.CUIIO_VERS, D.CUATM, D.CFP, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,

 
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND IN ('400') THEN  CIS2.NVAL(D.COL4)  ELSE 0 END))  AS COL2,
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150') THEN  CIS2.NVAL(D.COL1) END))  AS COL3,
  
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150','160','170') THEN  CIS2.NVAL(D.COL1) END))- 
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1125) AND D.RIND IN ('200') THEN CIS2.NVAL(D.COL1) END))+
(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1126) AND D.RIND IN ('330') THEN CIS2.NVAL(D.COL2) END))-
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1126) AND D.RIND IN ('330') THEN CIS2.NVAL(D.COL1) END)))+
 
(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1126) AND D.RIND IN ('340') THEN CIS2.NVAL(D.COL2) END))-
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1126) AND D.RIND IN ('340') THEN CIS2.NVAL(D.COL1) END)))  AS COL4,
  
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150','160','170') THEN  CIS2.NVAL(D.COL1) END))- 
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1125) AND D.RIND IN ('200') THEN CIS2.NVAL(D.COL1) END))+
(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1126) AND D.RIND IN ('330') THEN CIS2.NVAL(D.COL2) END))-
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1126) AND D.RIND IN ('330') THEN CIS2.NVAL(D.COL1) END)))+
 
(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1126) AND D.RIND IN ('340') THEN CIS2.NVAL(D.COL2) END))-
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1126) AND D.RIND IN ('340') THEN CIS2.NVAL(D.COL1) END)))-
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1125) AND D.RIND IN ('220') THEN CIS2.NVAL(D.COL1) END))-
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1125) AND D.RIND IN ('240') THEN CIS2.NVAL(D.COL1) END))-
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1125) AND D.RIND IN ('290') THEN CIS2.NVAL(D.COL1) END))+
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1125) AND D.RIND IN ('294') THEN CIS2.NVAL(D.COL1) END))+
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('180') THEN CIS2.NVAL(D.COL1) END))   AS COL5 
 

 

 
FROM   
    CIS2.VW_DATA_ALL_COEF D       
        INNER JOIN CIS2.RENIM R ON R.CUIIO = D.CUIIO AND R.CUIIO_VERS = D.CUIIO_VERS
WHERE
  D.FORM IN (64)             AND 
  D.FORM_VERS = :PFORM_VERS  AND      
  D.PERIOADA =:pPERIOADA AND
 -- D.CUATM_FULL LIKE '%'||:pCOD_CUATM||';%'   AND
  D.CAPITOL IN (100,1123,1124,1125,1126,1127,1128,1129) 
--  AND D.CUIIO=40209448

 GROUP BY D.CUIIO, D.CUIIO_VERS, D.CUATM, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,SUBSTR(R.CAEM2,2,4),D.CFP
 
HAVING
 (
   SUM(CASE WHEN D.ID_MD IN (62382) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) =  1 
   OR 
   SUM(CASE WHEN D.ID_MD IN (114171,62413) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) >  0  
      )
 )DD

-------------------------------------------------------------------------------

-- INNER JOIN CIS2.VW_CL_CAEM2 C ON SUBSTR( C.CODUL,2,4)  = CASE WHEN DD.CAEM2_ACTUALIZAT IS NULL THEN DD.CAEM2 ELSE DD.CAEM2_ACTUALIZAT END
-- INNER JOIN CIS2.VW_CL_CAEM2 CC ON  (C.FULL_CODE LIKE '%'||CC.CODUL||';%') 

INNER JOIN (
    SELECT
CODUL, 
DENUMIRE, 
GRUPA, 
ORDINE, 
FULL_CODE, 
NUM_CODE, 
PRIM                
                FROM  CIS2.VW_CL_CAEM2
                
               
                
                WHERE 
                
                

                CODUL LIKE 'C%'
               
               
         
                
              
             
                
                
                
    ) C ON SUBSTR(C.CODUL,2,4)  = DD.CAEM_FINAL
       
    
     INNER JOIN CIS2.VW_CL_CAEM2 CC ON (C.FULL_CODE LIKE '%'||CC.CODUL||';%') 
 INNER JOIN CIS2.VW_CL_CFP CF ON CF.CODUL = DD.CFP                 
 INNER JOIN CIS2.VW_CL_CFP CFF ON (CF.FULL_CODE LIKE '%'||CFF.CODUL||';%')
         
 WHERE 
  (DD.FORM=:pFORM) AND
  (DD.FORM_VERS=:pFORM_VERS) AND
  (:pID_MDTABLE=:pID_MDTABLE) AND
 -- (DD.CUATM_FULL LIKE '%'||:pCOD_CUATM||';%') AND   
  DD.PERIOADA IN (:pPERIOADA) 
 -- AND DD.CUIIO=40209448
--  AND 
--  CC.CODUL IN ('00000')
 AND CFF.CODUL IN ('00','11','14','20','22','28')
   GROUP BY
   CC.FULL_CODE,
   CC.DENUMIRE,
   CC.CODUL,
    CFF.CODUL,
    CFF.DENUMIRE

ORDER BY 
CFF.CODUL,
CC.CODUL
)

WHERE NR_ROW NOT IN '00000'    
    
  