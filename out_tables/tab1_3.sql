SELECT 
D.CUIIO,
SUM(R400_C1)  R400_C1, 
SUM(R150_C1)  R150_C1,
SUM(PERS)    PERS
FROM
(
SELECT 
D.CUIIO,
SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND IN ('400') THEN  CIS2.NVAL(D.COL3) END)  AS R400_C1,
SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150') THEN  CIS2.NVAL(D.COL1) END)  AS R150_C1,
 (
 
 SELECT  CASE WHEN DD.COL4 IS NOT NULL THEN ROUND(DD.COL4) ELSE 0 END 
 FROM
   CIS2.DATA_ALL DD
 WHERE
   DD.PERIOADA IN (D.PERIOADA) AND
   DD.FORM=D.FORM AND
   DD.ID_MD IN (69986) AND
   DD.CUIIO IN (D.CUIIO)) AS PERS
  
FROM   
    CIS2.VW_DATA_ALL D       
        INNER JOIN CIS2.RENIM R ON R.CUIIO = D.CUIIO AND R.CUIIO_VERS = D.CUIIO_VERS
WHERE
  D.FORM IN (64)             AND 
  D.FORM_VERS = :PFORM_VERS  AND      
  D.PERIOADA =:pPERIOADA  
  AND D.CAPITOL IN (100,1123,1124,1125,1126,1127,1128,1129)
  
  
  --  without  CAP SR 1 or 5 639613078.8	639613078.8
  --  with     CAP SR 1 or 5 639613078.8	639613078.8
  -- with             person 639247383.6	639247383.6


   GROUP BY D.CUIIO,D.CUIIO_VERS, D.CUATM,D.PERIOADA,D.FORM_VERS,D.FORM,CUATM_FULL
  
    HAVING 
  
   (
   SUM(CASE WHEN D.ID_MD IN (62382) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) =  1 
   OR 
   SUM(CASE WHEN D.ID_MD IN (114171,62413) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) >  0  
      )
      
      ) D
      
      GROUP BY
      D.CUIIO
      
