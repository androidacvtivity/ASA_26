-- Oracle 11g / Tab.3.5 ASA 2025
-- FORMAT CA IN EXCEL: indicatori pe randuri, CFOJ in coloanele COL2..COL16.
-- COL1 = TOTAL, COL2 = 420, COL3 = 500+510+520, COL4 = 530,
-- COL5 = cooperative 540+541+550+560, COL6 = 540, COL7 = 541,
-- COL8 = 550, COL9 = 560, COL10 = 590, COL11 = 620,
-- COL12 = 690, COL13 = 871, COL14 = 880, COL15 = 993, COL16 = 996.
-- ATENTIE: COL5 este subtotal al COL6..COL9; nu se aduna din nou in TOTAL.
-- Pastreaza maparea oferita: R400_C1=D.COL3, R400_C2=D.COL4,
-- R400_C3=D.COL5, R150_C1=D.COL1.
-- GROUP BY original: CUIIO + CFP + CFOJ (nu eliminam CFP).

WITH
DATE_FIRME AS (
    SELECT
        D.CUIIO,
        D.CFP,
        TRIM(TO_CHAR(D.CFOJ)) AS CFOJ,
        SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400'
                 THEN CIS2.NVAL(D.COL3) END) AS R400_C1,
        SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400'
                 THEN CIS2.NVAL(D.COL4) END) AS R400_C2,
        SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400'
                 THEN CIS2.NVAL(D.COL5) END) AS R400_C3,
        SUM(CASE WHEN D.CAPITOL = 1124 AND D.RIND = '150'
                 THEN CIS2.NVAL(D.COL1) END) AS R150_C1
    FROM CIS2.VW_DATA_ALL D
    INNER JOIN CIS2.RENIM R
        ON R.CUIIO = D.CUIIO
       AND R.CUIIO_VERS = D.CUIIO_VERS
    WHERE D.FORM = 64
      AND D.FORM_VERS = :PFORM_VERS
      AND D.PERIOADA = :pPERIOADA
      AND D.CAPITOL IN (100, 1123, 1124, 1125, 1126, 1127, 1128, 1129)
    GROUP BY D.CUIIO, D.CFP, TRIM(TO_CHAR(D.CFOJ))
    HAVING
           SUM(CASE WHEN D.ID_MD = 62382 AND D.COL1 IS NOT NULL
                    THEN D.COL1 ELSE 0 END) = 1
        OR SUM(CASE WHEN D.ID_MD IN (114171, 62413)
                         AND D.COL1 IS NOT NULL
                    THEN D.COL1 ELSE 0 END) > 0
),
GRUPE_CFOJ AS (
    SELECT 2 AS ORD, CAST('420' AS VARCHAR2(20)) AS GRUPA,
           CAST('420' AS VARCHAR2(5)) AS CFOJ FROM DUAL
    UNION ALL SELECT  3, '500+510+520', '500' FROM DUAL
    UNION ALL SELECT  3, '500+510+520', '510' FROM DUAL
    UNION ALL SELECT  3, '500+510+520', '520' FROM DUAL
    UNION ALL SELECT  4, '530', '530' FROM DUAL
    UNION ALL SELECT  5, '540+541+550+560', '540' FROM DUAL
    UNION ALL SELECT  5, '540+541+550+560', '541' FROM DUAL
    UNION ALL SELECT  5, '540+541+550+560', '550' FROM DUAL
    UNION ALL SELECT  5, '540+541+550+560', '560' FROM DUAL
    UNION ALL SELECT  6, '540', '540' FROM DUAL
    UNION ALL SELECT  7, '541', '541' FROM DUAL
    UNION ALL SELECT  8, '550', '550' FROM DUAL
    UNION ALL SELECT  9, '560', '560' FROM DUAL
    UNION ALL SELECT 10, '590', '590' FROM DUAL
    UNION ALL SELECT 11, '620', '620' FROM DUAL
    UNION ALL SELECT 12, '690', '690' FROM DUAL
    UNION ALL SELECT 13, '871', '871' FROM DUAL
    UNION ALL SELECT 14, '880', '880' FROM DUAL
    UNION ALL SELECT 15, '993', '993' FROM DUAL
    UNION ALL SELECT 16, '996', '996' FROM DUAL
),
DATE_GRUPATE AS (
    -- Total: include toate CFOJ (chiar daca nu figureaza in cele 15 grupe).
    SELECT 1 AS ORD_CFOJ, F.CUIIO,
           F.R400_C1, F.R400_C2, F.R400_C3, F.R150_C1
    FROM DATE_FIRME F

    UNION ALL

    -- Cele 15 grupe din Excel. LEFT JOIN pastreaza si categoriile fara date.
    SELECT G.ORD AS ORD_CFOJ, F.CUIIO,
           F.R400_C1, F.R400_C2, F.R400_C3, F.R150_C1
    FROM GRUPE_CFOJ G
    LEFT JOIN DATE_FIRME F ON F.CFOJ = G.CFOJ
),
SUME_CFOJ AS (
    SELECT
        ORD_CFOJ,
        COUNT(DISTINCT CUIIO) AS CNT,
        SUM(R400_C1) AS R400_C1,
        SUM(R400_C2) AS R400_C2,
        SUM(R400_C3) AS R400_C3,
        SUM(R150_C1) AS R150_C1
    FROM DATE_GRUPATE
    GROUP BY ORD_CFOJ
),
RANDURI AS (
    SELECT 1 AS ORD_RAND, 'Numarul intreprinderilor total' AS NUME_ROW,
           '1' AS NR_ROW FROM DUAL
    UNION ALL SELECT 2, 'TOTAL', '400, Col.1' FROM DUAL
    UNION ALL SELECT 3, 'TOTAL', '400, Col.2' FROM DUAL
    UNION ALL SELECT 4, 'TOTAL', '400, Col.3' FROM DUAL
    UNION ALL SELECT 5, 'Venituri din vanzari', '150, Col.1' FROM DUAL
),
VALORI AS (
    SELECT
        R.ORD_RAND,
        R.NUME_ROW,
        R.NR_ROW,
        G.ORD_CFOJ,
        CASE R.ORD_RAND
            WHEN 1 THEN G.CNT
            WHEN 2 THEN G.R400_C1
            WHEN 3 THEN G.R400_C2
            WHEN 4 THEN G.R400_C3
            WHEN 5 THEN G.R150_C1
        END AS VALOARE
    FROM RANDURI R
    CROSS JOIN SUME_CFOJ G
)
SELECT
    V.NUME_ROW AS DENUMIRE_INDICATOR,
    V.NR_ROW AS RIND,
    MAX(CASE WHEN V.ORD_CFOJ =  1 THEN V.VALOARE END) AS COL1,  -- TOTAL
    MAX(CASE WHEN V.ORD_CFOJ =  2 THEN V.VALOARE END) AS COL2,  -- 420
    MAX(CASE WHEN V.ORD_CFOJ =  3 THEN V.VALOARE END) AS COL3,  -- 500+510+520
    MAX(CASE WHEN V.ORD_CFOJ =  4 THEN V.VALOARE END) AS COL4,  -- 530
    MAX(CASE WHEN V.ORD_CFOJ =  5 THEN V.VALOARE END) AS COL5,  -- 540+541+550+560
    MAX(CASE WHEN V.ORD_CFOJ =  6 THEN V.VALOARE END) AS COL6,  -- 540
    MAX(CASE WHEN V.ORD_CFOJ =  7 THEN V.VALOARE END) AS COL7,  -- 541
    MAX(CASE WHEN V.ORD_CFOJ =  8 THEN V.VALOARE END) AS COL8,  -- 550
    MAX(CASE WHEN V.ORD_CFOJ =  9 THEN V.VALOARE END) AS COL9,  -- 560
    MAX(CASE WHEN V.ORD_CFOJ = 10 THEN V.VALOARE END) AS COL10, -- 590
    MAX(CASE WHEN V.ORD_CFOJ = 11 THEN V.VALOARE END) AS COL11, -- 620
    MAX(CASE WHEN V.ORD_CFOJ = 12 THEN V.VALOARE END) AS COL12, -- 690
    MAX(CASE WHEN V.ORD_CFOJ = 13 THEN V.VALOARE END) AS COL13, -- 871
    MAX(CASE WHEN V.ORD_CFOJ = 14 THEN V.VALOARE END) AS COL14, -- 880
    MAX(CASE WHEN V.ORD_CFOJ = 15 THEN V.VALOARE END) AS COL15, -- 993
    MAX(CASE WHEN V.ORD_CFOJ = 16 THEN V.VALOARE END) AS COL16  -- 996
FROM VALORI V
GROUP BY V.ORD_RAND, V.NUME_ROW, V.NR_ROW
ORDER BY V.ORD_RAND;
