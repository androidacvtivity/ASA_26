-- Oracle 11g - SELECT total indicatori, dupa formula furnizata.
-- Pastrate CUIIO, CFP, CFOJ, JOIN, filtrare si HAVING originale.
-- Adaugate randurile solicitate din capitolul 1125 (2911...310)
-- si randurile 320, 330, 340, 350 din capitolul 1126 (COL1).
-- Corectat R270_C1: rand 270, nu 260.
-- Nu contine INSERT INTO; nu a fost executat pe baza Oracle.

SELECT
    COUNT(DISTINCT D.CUIIO) AS CNT,
    SUM(D.R170_C1)  AS R170_C1,
    SUM(D.R210_C1)  AS R210_C1,
    SUM(D.R220_C1)  AS R220_C1,
    SUM(D.R221_C1)  AS R221_C1,
    SUM(D.R222_C1)  AS R222_C1,
    SUM(D.R240_C1)  AS R240_C1,
    SUM(D.R241_C1)  AS R241_C1,
    SUM(D.R242_C1)  AS R242_C1,
    SUM(D.R243_C1)  AS R243_C1,
    SUM(D.R260_C1)  AS R260_C1,
    SUM(D.R270_C1)  AS R270_C1,
    SUM(D.R280_C1)  AS R280_C1,
    SUM(D.R290_C1)  AS R290_C1,
    SUM(D.R291_C1)  AS R291_C1,
    SUM(D.R2911_C1) AS R2911_C1,
    SUM(D.R2912_C1) AS R2912_C1,
    SUM(D.R292_C1)  AS R292_C1,
    SUM(D.R293_C1)  AS R293_C1,
    SUM(D.R2931_C1) AS R2931_C1,
    SUM(D.R295_C1)  AS R295_C1,
    SUM(D.R296_C1)  AS R296_C1,
    SUM(D.R2961_C1) AS R2961_C1,
    SUM(D.R2962_C1) AS R2962_C1,
    SUM(D.R297_C1)  AS R297_C1,
    SUM(D.R300_C1)  AS R300_C1,
    SUM(D.R310_C1)  AS R310_C1,
    SUM(D.R320_C1)  AS R320_C1,
    SUM(D.R330_C1)  AS R330_C1,
    SUM(D.R340_C1)  AS R340_C1,
    SUM(D.R350_C1)  AS R350_C1,
    SUM(D.R400_C1)  AS R400_C1,
    SUM(D.R400_C2)  AS R400_C2,
    SUM(D.R400_C3)  AS R400_C3,
    SUM(D.R150_C1)  AS R150_C1
FROM (
    SELECT
        D.CUIIO,
        D.CFP,
        D.CFOJ,
        SUM(CASE WHEN D.CAPITOL = 1124 AND D.RIND = '170' THEN CIS2.NVAL(D.COL1) END) AS R170_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '210' THEN CIS2.NVAL(D.COL1) END) AS R210_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '220' THEN CIS2.NVAL(D.COL1) END) AS R220_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '221' THEN CIS2.NVAL(D.COL1) END) AS R221_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '222' THEN CIS2.NVAL(D.COL1) END) AS R222_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '240' THEN CIS2.NVAL(D.COL1) END) AS R240_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '241' THEN CIS2.NVAL(D.COL1) END) AS R241_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '242' THEN CIS2.NVAL(D.COL1) END) AS R242_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '243' THEN CIS2.NVAL(D.COL1) END) AS R243_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '260' THEN CIS2.NVAL(D.COL1) END) AS R260_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '270' THEN CIS2.NVAL(D.COL1) END) AS R270_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '280' THEN CIS2.NVAL(D.COL1) END) AS R280_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '290' THEN CIS2.NVAL(D.COL1) END) AS R290_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '291' THEN CIS2.NVAL(D.COL1) END) AS R291_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '2911' THEN CIS2.NVAL(D.COL1) END) AS R2911_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '2912' THEN CIS2.NVAL(D.COL1) END) AS R2912_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '292' THEN CIS2.NVAL(D.COL1) END) AS R292_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '293' THEN CIS2.NVAL(D.COL1) END) AS R293_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '2931' THEN CIS2.NVAL(D.COL1) END) AS R2931_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '295' THEN CIS2.NVAL(D.COL1) END) AS R295_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '296' THEN CIS2.NVAL(D.COL1) END) AS R296_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '2961' THEN CIS2.NVAL(D.COL1) END) AS R2961_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '2962' THEN CIS2.NVAL(D.COL1) END) AS R2962_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '297' THEN CIS2.NVAL(D.COL1) END) AS R297_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '300' THEN CIS2.NVAL(D.COL1) END) AS R300_C1,
        SUM(CASE WHEN D.CAPITOL = 1125 AND D.RIND = '310' THEN CIS2.NVAL(D.COL1) END) AS R310_C1,
        SUM(CASE WHEN D.CAPITOL = 1126 AND D.RIND = '320' THEN CIS2.NVAL(D.COL1) END) AS R320_C1,
        SUM(CASE WHEN D.CAPITOL = 1126 AND D.RIND = '330' THEN CIS2.NVAL(D.COL1) END) AS R330_C1,
        SUM(CASE WHEN D.CAPITOL = 1126 AND D.RIND = '340' THEN CIS2.NVAL(D.COL1) END) AS R340_C1,
        SUM(CASE WHEN D.CAPITOL = 1126 AND D.RIND = '350' THEN CIS2.NVAL(D.COL1) END) AS R350_C1,
        SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400' THEN CIS2.NVAL(D.COL3) END) AS R400_C1,
        SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400' THEN CIS2.NVAL(D.COL4) END) AS R400_C2,
        SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400' THEN CIS2.NVAL(D.COL5) END) AS R400_C3,
        SUM(CASE WHEN D.CAPITOL = 1124 AND D.RIND = '150' THEN CIS2.NVAL(D.COL1) END) AS R150_C1
    FROM CIS2.VW_DATA_ALL D
    INNER JOIN CIS2.RENIM R
        ON R.CUIIO = D.CUIIO
       AND R.CUIIO_VERS = D.CUIIO_VERS
    WHERE D.FORM IN (64)
      AND D.FORM_VERS = :PFORM_VERS
      AND D.PERIOADA = :pPERIOADA
      AND D.CAPITOL IN (100, 1123, 1124, 1125, 1126, 1127, 1128, 1129)
    GROUP BY D.CUIIO, D.CFP, D.CFOJ
    HAVING (
           SUM(CASE WHEN D.ID_MD = 62382 AND D.COL1 IS NOT NULL
                    THEN D.COL1 ELSE 0 END) = 1
        OR SUM(CASE WHEN D.ID_MD IN (114171, 62413) AND D.COL1 IS NOT NULL
                    THEN D.COL1 ELSE 0 END) > 0
    )
) D;
