-- Oracle 11g - SELECT simplu pentru verificare Tab.3.5.
-- Fara INSERT INTO, fara WITH. Logica de baza este exact cea furnizata.
-- Randuri: CNT, R400_C1, R400_C2, R400_C3, R150_C1.
-- Coloane CFOJ: COL1=TOTAL, COL2=420, COL3=500+510+520, COL4=530,
-- COL5=540+541+550+560, COL6=540, COL7=541, COL8=550, COL9=560,
-- COL10=590, COL11=620, COL12=690+430+450+700+996, COL13=871, COL14=880,
-- COL15=993, COL16=996.
-- COL5 este subtotal pentru COL6..COL9 si nu se aduna separat la TOTAL.
-- CFOJ 996 este intentionat inclus atat in COL12, cat si in COL16.
-- COL1 se calculeaza independent: COUNT(DISTINCT CUIIO), nu suma grupelor.

SELECT
    X.INDICATOR,
    X.RIND,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT X.CUIIO)
         ELSE SUM(X.VALOARE) END AS COL1,  -- TOTAL

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '420' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '420' THEN X.VALOARE END) END AS COL2,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ IN ('500','510','520') THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ IN ('500','510','520') THEN X.VALOARE END) END AS COL3,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '530' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '530' THEN X.VALOARE END) END AS COL4,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ IN ('540','541','550','560') THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ IN ('540','541','550','560') THEN X.VALOARE END) END AS COL5,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '540' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '540' THEN X.VALOARE END) END AS COL6,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '541' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '541' THEN X.VALOARE END) END AS COL7,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '550' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '550' THEN X.VALOARE END) END AS COL8,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '560' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '560' THEN X.VALOARE END) END AS COL9,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '590' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '590' THEN X.VALOARE END) END AS COL10,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '620' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '620' THEN X.VALOARE END) END AS COL11,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ IN ('690','430','450','700','996') THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ IN ('690','430','450','700','996') THEN X.VALOARE END) END AS COL12,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '871' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '871' THEN X.VALOARE END) END AS COL13,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '880' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '880' THEN X.VALOARE END) END AS COL14,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '993' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '993' THEN X.VALOARE END) END AS COL15,

    CASE WHEN X.ORD = 1 THEN COUNT(DISTINCT CASE WHEN X.CFOJ = '996' THEN X.CUIIO END)
         ELSE SUM(CASE WHEN X.CFOJ = '996' THEN X.VALOARE END) END AS COL16

FROM (
    SELECT
        R.ORD,
        R.INDICATOR,
        R.RIND,
        D.CUIIO,
        TRIM(TO_CHAR(D.CFOJ)) AS CFOJ,
        CASE R.ORD
            WHEN 2 THEN D.R400_C1
            WHEN 3 THEN D.R400_C2
            WHEN 4 THEN D.R400_C3
            WHEN 5 THEN D.R150_C1
        END AS VALOARE
    FROM (
        SELECT
            D.CUIIO,
            D.CFP,
            D.CFOJ,
            SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400'
                     THEN CIS2.NVAL(D.COL3) END) AS R400_C1,
            SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400'
                     THEN CIS2.NVAL(D.COL4) END) AS R400_C2,
            SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400'
                     THEN CIS2.NVAL(D.COL5) END) AS R400_C3,
            SUM(CASE WHEN D.CAPITOL = 1124 AND D.RIND = '150'
                     THEN CIS2.NVAL(D.COL1) END) AS R150_C1
        FROM CIS2.VW_DATA_ALL D
        INNER JOIN CIS2.RENIM R
            ON R.CUIIO = D.CUIIO
           AND R.CUIIO_VERS = D.CUIIO_VERS
        WHERE D.FORM IN (64)
          AND D.FORM_VERS = :PFORM_VERS
          AND D.PERIOADA = :pPERIOADA
          AND D.CAPITOL IN (100, 1123, 1124, 1125, 1126, 1127, 1128, 1129)
        GROUP BY D.CUIIO, D.CFP, D.CFOJ
        HAVING (
               SUM(CASE WHEN D.ID_MD = 62382 AND D.COL1 IS NOT NULL
                        THEN D.COL1 ELSE 0 END) = 1
            OR SUM(CASE WHEN D.ID_MD IN (114171, 62413) AND D.COL1 IS NOT NULL
                        THEN D.COL1 ELSE 0 END) > 0
        )
    ) D
    CROSS JOIN (
        SELECT 1 AS ORD, 'CNT' AS INDICATOR, '01' AS RIND FROM DUAL
        UNION ALL SELECT 2, 'R400_C1', '400, Col.1' FROM DUAL
        UNION ALL SELECT 3, 'R400_C2', '400, Col.2' FROM DUAL
        UNION ALL SELECT 4, 'R400_C3', '400, Col.3' FROM DUAL
        UNION ALL SELECT 5, 'R150_C1', '150, Col.1' FROM DUAL
    ) R
) X
GROUP BY X.ORD, X.INDICATOR, X.RIND
ORDER BY X.ORD;
