),
-- Datele de baza sunt filtrate cu aceiasi parametri din query-ul initial.
DATE_BAZA AS
(
    SELECT
        D.CUIIO, D.CUIIO_VERS, D.CUATM, D.CFP, D.CFOJ,
        D.CAPITOL, D.RIND, D.ID_MD,
        D.COL1, D.COL3, D.COL4, D.COL5,
        D.COL8, D.COL9, D.COL10
    FROM CIS2.VW_DATA_ALL D
    WHERE D.FORM = 64
      AND D.FORM_VERS = :pFORM_VERS
      AND D.PERIOADA = :pPERIOADA
      AND D.CUATM_FULL LIKE '%' || :pCOD_CUATM || ';%'
      AND D.CAPITOL IN (1123,1124,1125,1126,1127,1128)
),
-- Personalul din randul 400 COL4 (exact sursa originala).
-- Prima grupare este pastrata pentru numarul intreprinderilor.
INTREPRINDERI AS
(
    SELECT
        D.CUIIO, D.CUATM, D.CFP, D.CFOJ,
        SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400'
                 THEN D.COL4 ELSE 0 END) AS PERS
    FROM DATE_BAZA D
    GROUP BY D.CUIIO, D.CUATM, D.CFP, D.CFOJ
),
-- A doua grupare reproduce cheia folosita de subinterogarea DD initiala.
PERSONAL_DETALII AS
(
    SELECT
        D.CUIIO, D.CUIIO_VERS, D.CUATM, D.CFOJ,
        SUM(CASE WHEN D.CAPITOL = 1127 AND D.RIND = '400'
                 THEN D.COL4 ELSE 0 END) AS PERS
    FROM DATE_BAZA D
    GROUP BY D.CUIIO, D.CUIIO_VERS, D.CUATM, D.CFOJ
),
-- Un singur rand: "Numarul intreprinderilor total", pastrind COUNT(DISTINCT).
TOTAL_INTREPRINDERI AS
(
    SELECT
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 THEN ROUND(E.CUIIO, 1) END) AS COL1,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('420') THEN ROUND(E.CUIIO, 1) END) AS COL2,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('500','510','520') THEN ROUND(E.CUIIO, 1) END) AS COL3,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('530') THEN ROUND(E.CUIIO, 1) END) AS COL4,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('540','541','550','560') THEN ROUND(E.CUIIO, 1) END) AS COL5,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('540') THEN ROUND(E.CUIIO, 1) END) AS COL6,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('541') THEN ROUND(E.CUIIO, 1) END) AS COL7,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('550') THEN ROUND(E.CUIIO, 1) END) AS COL8,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('560') THEN ROUND(E.CUIIO, 1) END) AS COL9,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('590') THEN ROUND(E.CUIIO, 1) END) AS COL10,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('620') THEN ROUND(E.CUIIO, 1) END) AS COL11,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('690','430','450','700','996') THEN ROUND(E.CUIIO, 1) END) AS COL12,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('871') THEN ROUND(E.CUIIO, 1) END) AS COL13,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('880') THEN ROUND(E.CUIIO, 1) END) AS COL14,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('993') THEN ROUND(E.CUIIO, 1) END) AS COL15,
        COUNT(DISTINCT CASE WHEN E.PERS BETWEEN 0 AND 9999999999 AND E.CFOJ IN ('996') THEN ROUND(E.CUIIO, 1) END) AS COL16
    FROM INTREPRINDERI E
    HAVING COUNT(*) > 0
),
-- Extragerea valorilor pentru indicatorii din Excel.
-- JOIN-ul pe capitol evita combinarea randurilor cu acelasi cod RIND.
DETALII_BAZA AS
(
    SELECT
        I.POZITIE, I.CAPITOL, I.RIND, I.NR_COL, I.NUME_ROW,
        D.CFOJ,
        ROUND(
            CASE
                WHEN D.CAPITOL IN (1124,1125,1126) AND I.NR_COL = 1
                    THEN D.COL1
                WHEN D.CAPITOL = 1127
                    THEN DECODE(I.NR_COL, 1,D.COL3, 2,D.COL4, 3,D.COL5)
                WHEN D.CAPITOL = 1128
                    THEN DECODE(I.NR_COL, 1,D.COL8, 2,D.COL9, 3,D.COL10)
            END
        ) AS VALOARE
    FROM DATE_BAZA D
    JOIN INDICATORI I
      ON I.CAPITOL = D.CAPITOL
     AND I.RIND = D.RIND
    JOIN PERSONAL_DETALII P
      ON P.CUIIO = D.CUIIO
     AND P.CUIIO_VERS = D.CUIIO_VERS
    WHERE D.CAPITOL IN (1124,1125,1126,1127,1128)
      AND D.ID_MD IN (
            69961,70181,70158,70168,70159,70184,70175,70182,70160,70179,70164,70165,70180,70161,70162,
            70176,70169,70172,70173,70177,70185,70156,70186,70183,70166,70167,70157,70170,70171,70174,
            70163,70187,70188,69979,70190,69980,69981,69982,69983,69984,69985,
            69986,70121,70109
      )
      AND P.PERS BETWEEN 0 AND 9999999999
      AND EXISTS (
          SELECT 1 FROM CIS2.MD_RIND RD
          WHERE RD.RIND = D.RIND AND RD.ID_MD = D.ID_MD
      )
      -- Pastreaza ambele legaturi CFOJ din SQL-ul initial;
      -- EXISTS evita multiplicarea randurilor inainte de SUM(DISTINCT).
      AND EXISTS (
          SELECT 1
          FROM CIS2.VW_CL_CFOJ C
          JOIN CIS2.VW_CL_CFOJ CL_PARINTE
            ON C.FULL_CODE LIKE '%' || CL_PARINTE.CODUL || ';%'
          WHERE C.CODUL = D.CFOJ
      )
),
-- Agregarea este facuta o singura data per indicator si CFOJ,
-- pastrind SUM(DISTINCT) din interogarea originala.
DETALII_AGREGATE AS
(
    SELECT
        B.POZITIE, B.CAPITOL, B.RIND, B.NR_COL, B.NUME_ROW,
        SUM(DISTINCT B.VALOARE) AS COL1,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('420') THEN B.VALOARE END) AS COL2,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('500','510','520') THEN B.VALOARE END) AS COL3,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('530') THEN B.VALOARE END) AS COL4,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('540','541','550','560') THEN B.VALOARE END) AS COL5,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('540') THEN B.VALOARE END) AS COL6,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('541') THEN B.VALOARE END) AS COL7,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('550') THEN B.VALOARE END) AS COL8,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('560') THEN B.VALOARE END) AS COL9,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('590') THEN B.VALOARE END) AS COL10,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('620') THEN B.VALOARE END) AS COL11,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('690','430','450','700','996') THEN B.VALOARE END) AS COL12,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('871') THEN B.VALOARE END) AS COL13,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('880') THEN B.VALOARE END) AS COL14,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('993') THEN B.VALOARE END) AS COL15,
        SUM(DISTINCT CASE WHEN B.CFOJ IN ('996') THEN B.VALOARE END) AS COL16
    FROM DETALII_BAZA B
    GROUP BY B.POZITIE, B.CAPITOL, B.RIND, B.NR_COL, B.NUME_ROW
),
-- Daca un indicator este zero / lipsa pe toate coloanele, il omitem,
-- dupa logica filtrului final din interogarea originala.
DETALII_RAPORT AS
(
    SELECT *
    FROM DETALII_AGREGATE A
    WHERE A.COL1>0 OR A.COL2>0 OR A.COL3>0 OR A.COL4>0 OR A.COL5>0 OR A.COL6>0 OR A.COL7>0 OR A.COL8>0 OR A.COL9>0 OR A.COL10>0 OR A.COL11>0 OR A.COL12>0 OR A.COL13>0 OR A.COL14>0 OR A.COL15>0 OR A.COL16>0
)
SELECT
    :pPERIOADA    AS PERIOADA,
    :pFORM        AS FORM,
    :pFORM_VERS   AS FORM_VERS,
    :pID_MDTABLE  AS ID_MDTABLE,
    :pCOD_CUATM   AS COD_CUATM,
    '0' AS NR_SECTIE,
    '0' AS NUME_SECTIE,
    '0' AS NR_SECTIE1,
    '0' AS NUME_SECTIE1,
    '0' AS NR_SECTIE2,
    '0' AS NUME_SECTIE2,
    '01~01' AS NR_ROW,
    TO_NUMBER('01.01') AS ORDINE,
    '0000000000000000' AS DECIMAL_POS,
    'Numarul intreprinderilor total' AS NUME_ROW,
    COL1, COL2, COL3, COL4, COL5, COL6, COL7, COL8, COL9, COL10, COL11, COL12, COL13, COL14, COL15, COL16
FROM TOTAL_INTREPRINDERI
UNION ALL
SELECT
    :pPERIOADA    AS PERIOADA,
    :pFORM        AS FORM,
    :pFORM_VERS   AS FORM_VERS,
    :pID_MDTABLE  AS ID_MDTABLE,
    :pCOD_CUATM   AS COD_CUATM,
    '0' AS NR_SECTIE,
    '0' AS NUME_SECTIE,
    '0' AS NR_SECTIE1,
    '0' AS NUME_SECTIE1,
    '0' AS NR_SECTIE2,
    '0' AS NUME_SECTIE2,
    A.RIND || ', Col.' || A.NR_COL || '~01.' || A.NR_COL AS NR_ROW,
    TO_NUMBER(A.CAPITOL || '.' || A.RIND || A.NR_COL) AS ORDINE,
    '0000000000000000' AS DECIMAL_POS,
    A.NUME_ROW,
    COL1, COL2, COL3, COL4, COL5, COL6, COL7, COL8, COL9, COL10, COL11, COL12, COL13, COL14, COL15, COL16
FROM DETALII_RAPORT A
;
