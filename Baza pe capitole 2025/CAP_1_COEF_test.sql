SELECT
    D.ANUL AS ANUL,
    D.CUIIO AS CUIIO,
    R.IDNO,
    R.DENUMIRE,
    R.CUATM,
    R.CFP,
    R.CFOJ,
    R.CAEM2,
    MAX(CASE WHEN D.CAPITOL IN (100) AND D.RIND NOT IN ('CD','-') THEN D.RIND ELSE NULL END) AS CAP_SR,
    SUM(CASE WHEN D.CAPITOL IN (100) AND D.RIND  IN ('CD') THEN D.COL1 ELSE NULL END) AS RIND_CD,
    MAX(CASE WHEN D.CAPITOL IN (1129) AND D.RIND IN ('8') THEN D.COL31 ELSE NULL END) AS CAEM_ACT,

    CASE WHEN SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150') THEN D.COL1 ELSE NULL END) = 0 THEN NULL
         ELSE SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150') THEN D.COL1 ELSE NULL END)
    END AS RIND_150

FROM
    CIS2.VW_DATA_ALL_COEF D
INNER JOIN
    CIS2.RENIM R ON R.CUIIO = D.CUIIO AND R.CUIIO_VERS = D.CUIIO_VERS
WHERE
    D.FORM IN (64)
    AND D.FORM_VERS IN (2000)
    AND D.PERIOADA = :pPERIOADA
   -- AND D.CUATM_FULL LIKE '%' || :pCOD_CUATM || ';%'
    AND D.CAPITOL IN (1124, 1129, 100)
    AND D.CUIIO IN (
        SELECT 
DISTINCT D.CUIIO 
FROM CIS2.DATA_ALL D

 WHERE (D.PERIOADA = :pPERIOADA)
            
              AND D.FORM IN (64)
              AND D.FORM_VERS IN (2000)
              AND D.ID_MD IN (62382,114171,62413)
              
              
              GROUP BY 
              D.CUIIO

 HAVING (
           SUM(CASE WHEN D.ID_MD = 62382 AND D.COL1 IS NOT NULL
                    THEN D.COL1 ELSE 0 END) = 1
        OR SUM(CASE WHEN D.ID_MD IN (114171, 62413) AND D.COL1 IS NOT NULL
                    THEN D.COL1 ELSE 0 END) > 0
    )
    )
GROUP BY
    D.ANUL,
    D.CUIIO,
    R.IDNO,
    R.DENUMIRE,
    R.CUATM,
    R.CFP,
    R.CFOJ,
    R.CAEM2
    
    
