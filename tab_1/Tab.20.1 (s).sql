INSERT INTO CIS2.TABLE_OUT 
(
  PERIOADA,
  FORM,
  FORM_VERS,
  ID_MDTABLE,
  COD_CUATM,
  NR_SECTIE,
  NUME_SECTIE,
  NR_SECTIE1,
  NUME_SECTIE1,
  NR_SECTIE2,
  NUME_SECTIE2,
  NR_ROW,
  ORDINE,
  DECIMAL_POS,
  NUME_ROW,  
 COL1, COL2, COL3,COL4,COL5, COL6, COL7, COL8, COL9, COL10, COL11,COL12, COL13, COL14, COL15, COL16, COL17, COL18,COL19
 )
 


SELECT 
:pPERIOADA AS PERIOADA,
:pFORM AS FORM,
:pFORM_VERS AS FORM_VERS,
:pID_MDTABLE AS ID_MDTABLE,
:pCOD_CUATM AS COD_CUATM,    
'0' AS NR_SECTIE,
'0' AS NUME_SECTIE,
'0' AS NR_SECTIE1,
'0' AS NUME_SECTIE1,
'0' AS NR_SECTIE2,
'0' AS NUME_SECTIE2,
CODUL  AS NR_ROW,
ROWNUM  AS ORDINE,
'2222222222222222222' AS DECIMAL_POS,
DENUMIRE AS NUME_ROW, COL1, COL2, COL3,COL4,COL5, COL6, COL7, COL8, COL9, COL10, COL11,COL12, COL13, COL14, COL15, COL16, COL17, COL18,COL19
FROM (
SELECT 
 
   CASE WHEN  CC.CODUL like '%0000' THEN CC.DENUMIRE END AS DENUMIRE,   
   CASE WHEN  Substr(CC.CODUL,1,1)||'0000' IS NOT NULL THEN Substr(CC.CODUL,1,1)||'0000' END AS CODUL, 
   CC.FULL_CODE AS ORDINE,
   NVAL(SUM(D.TOTAL_CAEM)) AS COL1,
   NVAL(SUM(D.B)) AS COL2,   NVAL(SUM(D.C)) AS COL3,    NVAL(SUM(D.D)) AS COL4,  NVAL(SUM(D.E)) AS COL5,  NVAL(SUM(D.F)) AS COL6,
   NVAL(SUM(D.G)) AS COL7,   NVAL(SUM(D.H)) AS COL8,    NVAL(SUM(D.I)) AS COL9,  
   NVAL(SUM(D.J)) AS COL10,
   NVAL(SUM(D.K)) AS COL11, 
   NVAL(SUM(D.L)) AS COL12,  
   NVAL(SUM(D.M)) AS COL13,  
   NVAL(SUM(D.N)) AS COL14,   
   NVAL(SUM(D.P)) AS COL15, 
   NVAL(SUM(D.Q)) AS COL16, 
   NVAL(SUM(D.R)) AS COL17,  
   NVAL(SUM(D.S)) AS COL18,  
   NVAL(SUM(D.ALTELE)) AS COL19
 FROM
(
SELECT 
 D.CUIIO,D.CUIIO_VERS, D.CUATM, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,
-- MAX(CASE WHEN  D.RIND IN ('8') AND D.CAPITOL IN (1129) THEN D.COL31 END )  AS CAEM2_ACTUALIZAT,
 MAX(SUBSTR(D.CAEM2,2,4))  AS CAEM2,
  CASE WHEN  MAX(CASE WHEN D.ID_MD = 61832 THEN D.COL31 END) IS NULL THEN 
 SUBSTR(R.CAEM2,2,4) ELSE  MAX(CASE WHEN D.ID_MD = 61832 THEN D.COL31 END) END  AS CAEM2_ACTUALIZAT,


 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND IN ('400') THEN D.COL3 ELSE NULL END)),1)  AS TOTAL_CAEM,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '0500' AND '0990' THEN D.COL3 ELSE NULL END)),1) AS B,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '1000' AND '3320' THEN D.COL3 ELSE NULL END)),1) AS C,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '3500' AND '3530' THEN D.COL3 ELSE NULL END)),1) AS D,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '3600' AND '3900' THEN D.COL3 ELSE NULL END)),1) AS E,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '4100' AND '4399' THEN D.COL3 ELSE NULL END)),1) AS F,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '4500' AND '4799' THEN D.COL3 ELSE NULL END)),1) AS G,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '4900' AND '5320' THEN D.COL3 ELSE NULL END)),1) AS H,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '5500' AND '5630' THEN D.COL3 ELSE NULL END)),1) AS I,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '5800' AND '6399' THEN D.COL3 ELSE NULL END)),1) AS J,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '6400' AND '6630'   
 THEN D.COL3 ELSE NULL END)),1) AS K,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '6800' AND '6832' THEN D.COL3 ELSE NULL END)),1) AS L,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '6900' AND '7500' THEN D.COL3 ELSE NULL END)),1) AS M,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '7700' AND '8299' THEN D.COL3 ELSE NULL END)),1) AS N,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '8500' AND '8560' THEN D.COL3 ELSE NULL END)),1) AS P,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '8600' AND '8899' THEN D.COL3 ELSE NULL END)),1) AS Q,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '9000' AND '9329' THEN D.COL3 ELSE NULL END)),1) AS R,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND  COL31 BETWEEN '9400' AND '9609' THEN D.COL3 ELSE NULL END)),1) AS S,
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND NOT IN ('400') AND ((COL31 BETWEEN '0100' AND '0322')  OR (COL31 BETWEEN '9700' AND '9820') 
 OR (COL31 IN '9900')) THEN D.COL3 ELSE NULL END)),1) AS ALTELE, 


 
 ROUND(CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (100)  AND D.RIND IN ('CD') THEN  D.COL1 ELSE 0 END)),1)  AS CD
 
FROM   
    CIS2.VW_DATA_ALL_COEF D       
            INNER JOIN CIS2.RENIM R ON R.CUIIO = D.CUIIO AND R.CUIIO_VERS = D.CUIIO_VERS
WHERE
  D.FORM IN (64)             AND 
  D.FORM_VERS = :PFORM_VERS  AND      
  D.PERIOADA =:pPERIOADA AND
  D.CUATM_FULL LIKE '%'||:pCOD_CUATM||';%'   AND
  D.CAPITOL IN (100,1123,1124,1125,1126,1127,1128,1129) --and d.cuiio in(38954908)
 -- AND (D.RIND LIKE ('4%') OR D.RIND IN ('8','CD'))--00','410','411','412','8')
 -- AND D.CUIIO=40209448
  GROUP BY D.CUIIO,D.CUIIO_VERS, D.CUATM, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,SUBSTR(R.CAEM2,2,4)
  
--  HAVING 
 --    SUM(CASE WHEN D.ID_MD IN (62382) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) =  1 
 --  OR 
 --  SUM(CASE WHEN D.ID_MD IN (114171,62413) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) >  0  
   
   ) D
   
 INNER JOIN (
 SELECT
CODUL, 
DENUMIRE, 
GRUPA, 
ORDINE, 
FULL_CODE, 
NUM_CODE, 
PRIM                
                FROM  CIS2.VW_CL_CAEM2
                
               
                
                WHERE 
                
                
(
                CODUL LIKE 'C%'
                OR CODUL LIKE 'B%'
                OR CODUL LIKE 'D%'
                OR CODUL LIKE 'E%'
                OR CODUL LIKE 'F%'
                OR CODUL LIKE 'G%'
                OR CODUL LIKE 'H%'
                OR CODUL LIKE 'I%'
               -- OR CODUL LIKE 'K%'
                OR CODUL LIKE 'J%'
                OR CODUL LIKE 'L%'
                OR CODUL LIKE 'M%'
             --   OR CODUL LIKE 'Q%'
              --  OR CODUL LIKE 'P%'
                OR CODUL LIKE 'N%'
               -- OR CODUL LIKE 'R%'
                OR CODUL LIKE 'S%'
                )
                
                AND 
                
                SUBSTR(CODUL,1,3) NOT IN ('S94','K65')
               -- AND 
              --  CODUL NOT IN ('K6419','K6411')
                
                
                
                
 ) C ON SUBSTR( C.CODUL,2,4) = D.CAEM2_ACTUALIZAT
 INNER JOIN CIS2.VW_CL_CAEM2 CC ON  (C.FULL_CODE LIKE '%'||CC.CODUL||';%') 
 
 WHERE 
  (D.FORM=:pFORM) AND
  (D.FORM_VERS=:pFORM_VERS) AND
  (:pID_MDTABLE=:pID_MDTABLE) AND
 -- (D.CUATM_FULL LIKE '%'||:pCOD_CUATM||';%') AND   
  D.PERIOADA IN (:pPERIOADA) 
  AND CC.CODUL IN (
'00000',
'B0000',
'C0000',
'D0000',
'E0000',
'F0000',
'G0000',
'H0000',
'I0000',
'J0000',
'K0000',
'L0000',
'M0000',
'N0000',
'P0000',
'Q0000',
'R0000',
'S0000'

   )
  
  GROUP BY   CC.FULL_CODE,    CC.DENUMIRE,   CC.CODUL   
    ORDER BY
  CC.FULL_CODE 

  )
  
  WHERE 
  DENUMIRE IS NOT NULL