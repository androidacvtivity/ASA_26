INSERT INTO CIS2.TABLE_OUT 
(
  PERIOADA,
  FORM,
  FORM_VERS,
  ID_MDTABLE,
  COD_CUATM,
  NR_SECTIE,
  NUME_SECTIE,
  NR_SECTIE1,
  NUME_SECTIE1,
  NR_SECTIE2,
  NUME_SECTIE2,
  NR_ROW,
  ORDINE,
  DECIMAL_POS,
  NUME_ROW,  
 COL1, COL2, COL3,COL4,COL5, COL6, COL7
)


SELECT 
 
:PPERIOADA AS PERIOADA,
:PFORM AS FORM,
:PFORM_VERS AS FORM_VERS,
:PID_MDTABLE AS ID_MDTABLE,
:PCOD_CUATM AS COD_CUATM,    
'0' AS  NR_SECTIE,
'0' AS  NUME_SECTIE,
'0' AS NR_SECTIE1,
'0' AS NUME_SECTIE1,
'0' AS NR_SECTIE2,
'0' AS NUME_SECTIE2, 
NR_ROW,
ROWNUM AS ORDINE,--||'~'||ORDINE
-- Primele 3 coloane sunt totaluri intregi, ultimele 4 sunt procente (1 zecimala).
'0001111' AS DECIMAL_POS,
NUME_ROW,
COL1, COL2, COL3,COL4,COL5, COL6, COL7
 FROM (

SELECT 
CODUL||'~'||COL1||'1' AS NR_ROW,
 1||ORDINE AS ORDINE,
'0000000' AS DECIMAL_POS,
 DENUMIRE AS NUME_ROW,
COL1, COL2, COL3,COL4,COL5, COL6, COL7
 FROM(
 
SELECT 
   CC.FULL_CODE,
   CASE WHEN  CC.CODUL LIKE '%0000' THEN CC.DENUMIRE END AS DENUMIRE,   
   CASE WHEN  SUBSTR(CC.CODUL,1,1)||'0000' IS NOT NULL THEN SUBSTR(CC.CODUL,1,1)||'0000' END AS CODUL, 
   CC.FULL_CODE AS ORDINE,
   -- Identic cu Tab.19: insumam valorile nerotunjite si rotunjim o singura data.
   CIS2.NVAL(ROUND(SUM(DD.CD),1))    AS COL1,
   CIS2.NVAL(ROUND(SUM(DD.COL2),1))  AS COL2,
   CIS2.NVAL(ROUND(SUM(DD.COL3),1))  AS COL3,
   
   CIS2.NVAL(SUM(CASE WHEN DD.R400 BETWEEN 1 AND 5  THEN DD.COL2 END ))  AS COL4,
   CIS2.NVAL(SUM(CASE WHEN DD.R400 BETWEEN 1 AND 20 THEN DD.COL2 END ))  AS COL5,
   CIS2.NVAL(SUM(CASE WHEN DD.R150 BETWEEN 1 AND 5  THEN DD.COL3 END ))  AS COL6,
   CIS2.NVAL(SUM(CASE WHEN DD.R150 BETWEEN 1 AND 20 THEN DD.COL3 END ))  AS COL7
  FROM

(
SELECT  
 DISTINCT 
 D.CUIIO,
 D.CUIIO_VERS, 
 MAX(SUBSTR(D.CAEM2,2,4)) AS CAEM2,
  CASE WHEN  MAX(CASE WHEN D.ID_MD = 61832 THEN D.COL31 END) IS NULL THEN 
 SUBSTR(R.CAEM2,2,4) ELSE  MAX(CASE WHEN D.ID_MD = 61832 THEN D.COL31 END) END  AS CAEM_FINAL,
 D.CUATM, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,
SUM(CASE WHEN D.CAPITOL IN (100) AND D.RIND IN ('CD') THEN D.COL1 ELSE 0 END) AS CD,
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND IN ('400') THEN  CIS2.NVAL(D.COL4)  ELSE 0 END))  AS COL2,
 CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150') THEN  CIS2.NVAL(D.COL1) END))  AS COL3,
 ROW_NUMBER() OVER(ORDER BY CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1124) AND D.RIND IN ('150') THEN  CIS2.NVAL(D.COL1) END)) DESC NULLS LAST) R150,
 ROW_NUMBER() OVER(ORDER BY CIS2.NVAL(SUM(CASE WHEN D.CAPITOL IN (1127) AND D.RIND IN ('400') THEN  CIS2.NVAL(D.COL4) END)) DESC NULLS LAST) R400
 
FROM   
    CIS2.VW_DATA_ALL_COEF D    
    INNER JOIN CIS2.RENIM R ON R.CUIIO = D.CUIIO AND R.CUIIO_VERS = D.CUIIO_VERS   
WHERE
  D.FORM IN (64)             AND 
  D.FORM_VERS = :PFORM_VERS  AND      
  D.PERIOADA =:PPERIOADA AND
  D.CUATM_FULL LIKE '%'||:PCOD_CUATM||';%'   AND
  -- Capitolul 1129 contine informatia CAEM actualizata (ID_MD=61832).
  D.CAPITOL IN (1123,1124,1125,1126,1127,1128,1129,100)
 --   AND D.CUIIO=40209448

 -- O singura inregistrare agregata per CUIIO / versiune, ca in Tab.19.
 GROUP BY D.CUIIO, D.CUIIO_VERS, D.CUATM, D.FORM,D.FORM_VERS,D.CUATM_FULL,D.PERIOADA,SUBSTR(R.CAEM2,2,4)
 HAVING  
 -- Aceeasi selectie a intreprinderilor ca in Tab.19.
 (
   SUM(CASE WHEN D.ID_MD IN (62382) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) =  1 
   OR 
   SUM(CASE WHEN D.ID_MD IN (114171,62413) AND D.COL1 IS NOT NULL THEN D.COL1 ELSE 0 END) >  0  
      )) DD 
      
      INNER JOIN (
    SELECT
CODUL, 
DENUMIRE, 
GRUPA, 
ORDINE, 
FULL_CODE, 
NUM_CODE, 
PRIM                
                FROM  CIS2.VW_CL_CAEM2
                
               
                
                WHERE 
                
                
(
                CODUL LIKE 'C%'
                OR CODUL LIKE 'B%'
                OR CODUL LIKE 'D%'
                OR CODUL LIKE 'E%'
                OR CODUL LIKE 'F%'
                OR CODUL LIKE 'G%'
                OR CODUL LIKE 'H%'
                OR CODUL LIKE 'I%'
                OR CODUL LIKE 'K%'
                OR CODUL LIKE 'J%'
                OR CODUL LIKE 'L%'
                OR CODUL LIKE 'M%'
                OR CODUL LIKE 'Q%'
                OR CODUL LIKE 'P%'
                OR CODUL LIKE 'N%'
                OR CODUL LIKE 'R%'
                OR CODUL LIKE 'S%'
                )
                
                AND 
                
                SUBSTR(CODUL,1,3) NOT IN ('S94','K65')
                AND 
                CODUL NOT IN ('K6419','K6411')
                
                
                
    ) C ON SUBSTR(C.CODUL,2,4)  = DD.CAEM_FINAL
    INNER JOIN CIS2.VW_CL_CAEM2 CC ON (C.FULL_CODE LIKE '%'||CC.CODUL||';%')
    
     WHERE 
  (DD.FORM=:pFORM) AND
  (DD.FORM_VERS=:pFORM_VERS) AND
  (:pID_MDTABLE=:pID_MDTABLE) 
  
    
     GROUP BY
    CC.FULL_CODE,
    CC.DENUMIRE,
    CC.CODUL
     
    ORDER BY 
    CC.CODUL
  )
  WHERE DENUMIRE IS NOT NULL)
  
  ORDER BY ORDINE
